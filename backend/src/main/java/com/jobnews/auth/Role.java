package com.jobnews.auth;

/**
 * [전체 흐름에서의 위치] 로그인한 사용자의 권한 등급입니다. users.role 컬럼에 이 값의
 * 이름(예: "ADMIN")이 그대로 저장됩니다(ai 패키지의 FilterReason과 같은 패턴 — 정해진
 * 값만 쓰게 해서 나중에 조건 조회/집계할 때 값이 흔들리지 않게 합니다).
 * 이번 범위에서는 이 값을 근거로 접근을 막는 로직(예: 관리자 전용 API)은 아직 없습니다 —
 * 값만 만들어두고, 실제로 활용하는 건 앞으로 만들 관리자 통계 대시보드 작업입니다.
 */
public enum Role {
    // 기본값. 일반 로그인 사용자.
    USER,
    // 통계 대시보드 등 관리자 전용 기능에 접근할 수 있는 계정. 가입으로 자동 부여되지
    // 않고, 운영자가 DB에 직접 UPDATE해서 수동으로만 지정합니다(infra/README.md 참고).
    ADMIN
}
